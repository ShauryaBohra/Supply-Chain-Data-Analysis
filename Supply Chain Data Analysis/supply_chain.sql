WITH sales_summary AS (
  SELECT s.product_id, s.customer_demographics, SUM(s.revenue_generated) AS total_revenue
  FROM Sales s
  GROUP BY s.product_id, s.customer_demographics
)
SELECT ss.customer_demographics, p.product_type, sup.supplier_name,
ROUND(AVG(sup.defect_rates), 2) AS avg_defect_rate,SUM(ss.total_revenue) AS total_revenue
FROM sales_summary ss
JOIN Products p ON ss.product_id = p.product_id
JOIN Logistics l ON p.product_id = l.product_id
JOIN Suppliers sup ON l.supplier_id = sup.supplier_id
GROUP BY ss.customer_demographics, p.product_type, sup.supplier_name
ORDER BY total_revenue DESC;
