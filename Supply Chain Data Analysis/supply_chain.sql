CREATE TABLE Sales ( 
sale_id INT PRIMARY KEY AUTO_INCREMENT, 
product_id INT, 
number_of_products_sold INT, 
revenue_generated DECIMAL(12,2), 
customer_demographics VARCHAR(50), 
FOREIGN KEY (product_id) REFERENCES Products(product_id) );

INSERT INTO Sales (product_id, number_of_products_sold, revenue_generated, customer_demographics)
SELECT p.product_id,r.`Number_products_sold`,r.`Revenue_generated`,
r.`Customer_demographics`
FROM supply_chain_data r
JOIN Products p 
ON r.SKU = p.sku;

select * from Sales;

CREATE TABLE Inventory (
    inventory_id INT PRIMARY KEY AUTO_INCREMENT,
    product_id INT,
    availability INT,
    stock_levels INT,
    order_quantities INT,
    FOREIGN KEY (product_id) REFERENCES Products(product_id)
);

INSERT INTO Inventory (product_id, availability, stock_levels, order_quantities)
SELECT p.product_id,r.`Availability`,r.`Stock_levels`,
r.`Order_quantities`
FROM supply_chain_data r
JOIN Products p 
ON r.sku = p.sku;

select * from Inventory;

